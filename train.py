#!/usr/bin/env python3
"""Train on Train, validate on Val, and save validation-selected checkpoints."""
import argparse
import json
import os
import random
from pathlib import Path

import numpy as np
import torch
from torch.utils.data import DataLoader, Subset

from qtra.data.loading import cdvqa_dataset, qag_dataset
from qtra.evaluation import evaluate
from qtra.factory import build_model, load_weights, read_config
from qtra.training import (
    configure_stage, epoch_record, make_optimizer, seed_worker, set_seed,
    train_epoch, validation_scores,
)


def parse_args():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", required=True)
    parser.add_argument("--clip-pretrained", required=True)
    parser.add_argument("--x3d-pretrained")
    parser.add_argument("--train-root", help="QAG training split directory")
    parser.add_argument("--val-root", help="QAG validation split directory")
    parser.add_argument("--cdvqa-root")
    parser.add_argument("--second-root")
    parser.add_argument("--output", required=True)
    source = parser.add_mutually_exclusive_group()
    source.add_argument("--init-checkpoint", help="Weights from the preceding stage")
    source.add_argument("--resume", help="Resume a checkpoint generated by this release trainer")
    parser.add_argument("--device", default="cuda")
    parser.add_argument("--workers", type=int, default=4)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--epochs", type=int, help="Override configured epoch count")
    parser.add_argument("--batch-size", type=int)
    parser.add_argument("--precision", choices=["fp32", "fp16", "bf16"])
    parser.add_argument("--limit-train", type=int, help="Debug only: cap training samples")
    parser.add_argument("--limit-val", type=int, help="Debug only: cap validation samples")
    return parser.parse_args()


def capture_rng(generator):
    state = np.random.get_state()
    return {
        "python": random.getstate(),
        "numpy": [state[0], state[1].tolist(), state[2], state[3], state[4]],
        "torch": torch.get_rng_state(),
        "cuda": torch.cuda.get_rng_state_all() if torch.cuda.is_available() else [],
        "loader": generator.get_state(),
    }


def restore_rng(state, generator):
    random.setstate(state["python"])
    ns = state["numpy"]
    np.random.set_state((ns[0], np.asarray(ns[1], dtype=np.uint32), ns[2], ns[3], ns[4]))
    torch.set_rng_state(state["torch"])
    if state["cuda"] and torch.cuda.is_available():
        torch.cuda.set_rng_state_all(state["cuda"])
    generator.set_state(state["loader"])


def save_checkpoint(payload, path):
    temporary = path.with_suffix(".tmp")
    torch.save(payload, temporary)
    os.replace(temporary, path)


def checkpoint_alias(source, destination):
    # Same-directory hard links avoid duplicating the same large checkpoint.
    import shutil
    temporary = destination.with_suffix(".tmp")
    try:
        os.link(source, temporary)
    except OSError:
        shutil.copyfile(source, temporary)
    os.replace(temporary, destination)


def main():
    args = parse_args()
    config = read_config(args.config)
    cfg = config["training"]
    for key, value in (("epochs", args.epochs), ("batch_size", args.batch_size), ("precision", args.precision)):
        if value is not None:
            cfg[key] = value
    if cfg["epochs"] < 1 or cfg["batch_size"] < 1 or cfg.get("grad_accum_steps", 1) < 1:
        raise ValueError("Epochs, batch size and accumulation steps must be positive.")
    output = Path(args.output)
    if output.exists() and any(output.iterdir()) and not args.resume:
        raise FileExistsError(f"Use a new output directory or --resume: {output}")
    for limit in (args.limit_train, args.limit_val):
        if limit is not None and limit < 1:
            raise ValueError("Debug sample limits must be positive.")
    stage = cfg["stage"]
    if stage not in ("baseline", "cdvqa") and not (args.init_checkpoint or args.resume):
        raise ValueError(f"Stage {stage} requires --init-checkpoint or --resume.")
    if stage in ("baseline", "cdvqa") and not (args.x3d_pretrained or args.init_checkpoint or args.resume):
        raise ValueError("Supply --x3d-pretrained when starting a fresh model.")
    set_seed(args.seed)
    device = torch.device(args.device)
    if config["task"] == "qag":
        if not args.train_root or not args.val_root:
            raise ValueError("QAG requires --train-root and --val-root.")
        train_set = qag_dataset(args.train_root, "Train")
        val_set = qag_dataset(args.val_root, "Val")
    else:
        if not args.cdvqa_root or not args.second_root:
            raise ValueError("CDVQA requires --cdvqa-root and --second-root.")
        train_set = cdvqa_dataset(args.cdvqa_root, args.second_root, "Train")
        val_set = cdvqa_dataset(args.cdvqa_root, args.second_root, "Val")
    if args.limit_train:
        train_set = Subset(train_set, range(min(args.limit_train, len(train_set))))
    if args.limit_val:
        val_set = Subset(val_set, range(min(args.limit_val, len(val_set))))
    generator = torch.Generator().manual_seed(args.seed)
    loader_options = dict(batch_size=cfg["batch_size"], num_workers=args.workers, pin_memory=device.type == "cuda")
    train_loader = DataLoader(train_set, shuffle=True, generator=generator, worker_init_fn=seed_worker, **loader_options)
    val_loader = DataLoader(val_set, shuffle=False, **loader_options)
    model = build_model(config["model"], args.clip_pretrained, args.x3d_pretrained)
    resume = None
    if args.resume:
        resume = load_weights(model, args.resume)
        if resume.get("format_version") != 1:
            raise ValueError("Use --init-checkpoint for development weights; --resume needs a release checkpoint.")
        previous = resume["config"]
        previous_train = {k: v for k, v in previous["training"].items() if k != "epochs"}
        current_train = {k: v for k, v in cfg.items() if k != "epochs"}
        if previous["model"] != config["model"] or previous_train != current_train:
            raise ValueError("Resume configuration differs from the saved run (only epochs may be extended).")
    elif args.init_checkpoint:
        missing = {
            "qtra": ("change_encoder.shared_qra.",),
            "global": ("answer_calibration.",),
            "grounding": ("dynamic_mask_decoder.", "dual_gate."),
            "evidence": ("mask_guided_answer.",),
        }.get(stage, ())
        load_weights(model, args.init_checkpoint, missing)
    model.to(device)
    scaler = torch.cuda.amp.GradScaler(enabled=device.type == "cuda" and cfg["precision"] != "fp32")
    start_epoch = 0 if resume is None else resume["epoch"] + 1
    best = {} if resume is None else resume["best"]
    if start_epoch >= cfg["epochs"]:
        raise ValueError("No remaining epochs; increase --epochs to continue.")
    output.mkdir(parents=True, exist_ok=True)
    # This file is newly generated metadata, not a rewritten historical log.
    (output / "config.json").write_text(json.dumps(config, indent=2) + "\n")
    (output / "arguments.json").write_text(json.dumps(vars(args), indent=2) + "\n")
    optimizer = None
    previous_phase = None
    for epoch in range(start_epoch, cfg["epochs"]):
        phase, groups, active = configure_stage(model, cfg, epoch)
        if phase != previous_phase:
            optimizer = make_optimizer(cfg, groups)
        if resume is not None:
            if phase == resume["phase"]:
                optimizer.load_state_dict(resume["optimizer_state"])
            scaler.load_state_dict(resume["scaler_state"])
            restore_rng(resume["rng"], generator)
            resume = None
        previous_phase = phase
        train_metrics = train_epoch(model, train_loader, optimizer, scaler, device, config["task"], cfg, active, epoch)
        val_metrics = evaluate(
            model, val_loader, device, config["task"], threshold=config.get("mask_threshold", 0.35),
            precision=cfg["precision"], desc=f"val {epoch}",
        )
        improved = []
        for name, value in validation_scores(val_metrics).items():
            if name not in best or value > best[name]["value"]:
                best[name] = {"value": value, "epoch": epoch}
                improved.append(name)
        payload = {
            "format_version": 1, "epoch": epoch, "phase": phase,
            "config": config, "model_state": model.state_dict(),
            "optimizer_state": optimizer.state_dict(), "scaler_state": scaler.state_dict(),
            "metrics": {"train": train_metrics, "val": val_metrics},
            "best": best, "rng": capture_rng(generator),
        }
        save_checkpoint(payload, output / "last.pth")
        for name in improved:
            checkpoint_alias(output / "last.pth", output / f"best_{name}.pth")
        record = epoch_record(epoch, phase, optimizer, train_metrics, val_metrics)
        with (output / "train_log.jsonl").open("a", encoding="utf-8") as handle:
            handle.write(json.dumps(record) + "\n")
        (output / "best_summary.json").write_text(json.dumps(best, indent=2) + "\n")
        (output / f"val_metrics_epoch{epoch}.json").write_text(json.dumps(val_metrics, indent=2) + "\n")
        print(json.dumps(record))


if __name__ == "__main__":
    main()
